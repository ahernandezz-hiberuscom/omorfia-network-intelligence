def points():
    """[(lat, lon, type_code), ...] for every competitor within 3 km of the group."""
    out = []
    for tok in _RAW.split(";"):
        la, lo, t = tok.split(",")
        out.append((float(la), float(lo), t))
    return out


def density(lat, lon, radii=(1.0, 2.0, 3.0)):
    """Competitor counts around a coordinate, one per radius. Haversine."""
    import math
    R = 6371.0
    p1 = math.radians(lat)
    out = [0] * len(radii)
    for la, lo, _ in points():
        p2 = math.radians(la)
        dp, dl = p2 - p1, math.radians(lo - lon)
        a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
        d = 2 * R * math.asin(math.sqrt(a))
        for i, r in enumerate(radii):
            if d <= r:
                out[i] += 1
    return out


